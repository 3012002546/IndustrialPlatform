export type SystemDataPageCopy = Record<string, string> & {
  [key in SystemDataPageKey]: string
}

/** Shared lookup for SystemData management pages; unknown enum values stay visible for diagnostics. */
export function systemDataEnumLabel(
  locale: SupportedLocale,
  value: string | null | undefined,
): string {
  if (value === null || value === undefined || value.length === 0) return '—'
  return localeMessages[locale].systemData.enums[value] ?? value
}

/** Returns a page dictionary without making page components carry fallback copy. */
export function systemDataPageCopy(locale: SupportedLocale, page: string): SystemDataPageCopy {
  return (localeMessages[locale].systemData.pages[page] ?? {}) as SystemDataPageCopy
}

export function interpolate(value: string, replacements: Record<string, string | number>): string {
  return Object.entries(replacements).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
    value,
  )
}
