export type SheetMessage = keyof typeof zh
export const useSheetCopy = () => {
  const locale = useLocalizationStore()
  return computed(() => (key: SheetMessage) => (locale.locale === 'en-US' ? en : zh)[key])
}
export class SheetError extends Error {
  constructor(readonly key: SheetMessage) {
    super(key)
  }
}
