export function useStudioCopy() {
  const locale = useLocalizationStore()
  return computed(
    () => (key: string) =>
      locale.locale === 'en-US'
        ? (english[key] ??
          key.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase()))
        : ((studioMessages['zh-CN'] as Record<string, string>)[key] ?? key),
  )
}
