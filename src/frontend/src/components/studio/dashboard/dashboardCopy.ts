export type DashboardTextKey = keyof (typeof dashboardMessages)['zh-CN']

export interface DashboardText {
  (key: string, params?: DashboardTextParams): string
  componentLabel(key: string): string
  categoryLabel(category: string): string
  propertyLabel(key: string): string
  optionLabel(value: unknown): string
}

export type DashboardTextRef = ComputedRef<DashboardText>

const categoryBySource: Record<string, keyof typeof dashboardCategoryLabels> = {
  基础: 'basic',
  图表: 'chart',
  工业: 'industrial',
  数据: 'data',
  basic: 'basic',
  chart: 'chart',
  industrial: 'industrial',
  data: 'data',
}

function interpolate(value: string, params: DashboardTextParams | undefined): string {
  if (!params) return value
  return value.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  )
}

function createDashboardText(locale: DashboardLocale): DashboardText {
  const messages = dashboardMessages[locale]
  const text = ((key: string, params?: DashboardTextParams) => {
    const value = messages[key as DashboardTextKey]
    // Unknown strings are returned unchanged so user text, NIds, business data
    // and contract enum values are never translated by accident.
    return interpolate(value ?? key, params)
  }) as DashboardText

  text.componentLabel = (key: string) => {
    const entry = dashboardComponentLabels[key as DashboardComponentKey]
    if (!entry) return key
    return locale === 'en-US' ? entry.en : entry.zh
  }
  text.categoryLabel = (category: string) => {
    const key = categoryBySource[category]
    if (!key) return category
    const entry = dashboardCategoryLabels[key]
    return locale === 'en-US' ? entry.en : entry.zh
  }
  text.propertyLabel = (key) => dashboardPropertyLabels[key]?.[locale === 'en-US' ? 1 : 0] ?? key
  text.optionLabel = (value) =>
    dashboardOptionLabels[String(value)]?.[locale === 'en-US' ? 1 : 0] ?? String(value)
  return text
}

/**
 * Dashboard-local copy with the same `computed(() => (key) => value)` shape as
 * `useStudioCopy`. Use `const t = useDashboardText()` and `t.value('back')`.
 */
export function useDashboardText(): DashboardTextRef {
  const localization = useLocalizationStore()
  return computed(() => createDashboardText(localization.locale as DashboardLocale))
}
