DECLARE @table sysname,@column sysname,@description nvarchar(4000);
DECLARE descriptions CURSOR LOCAL FAST_FORWARD FOR SELECT TableName,ColumnName,Description FROM @descriptions;
OPEN descriptions; FETCH NEXT FROM descriptions INTO @table,@column,@description;
WHILE @@FETCH_STATUS=0 BEGIN
IF EXISTS(SELECT 1 FROM sys.extended_properties WHERE class=1 AND major_id=OBJECT_ID(N'dbo.'+@table) AND minor_id=COALESCE(COLUMNPROPERTY(OBJECT_ID(N'dbo.'+@table),@column,'ColumnId'),0) AND name=N'MS_Description')
BEGIN
IF @column IS NULL EXEC sys.sp_updateextendedproperty @name=N'MS_Description',@value=@description,@level0type=N'SCHEMA',@level0name=N'dbo',@level1type=N'TABLE',@level1name=@table;
ELSE EXEC sys.sp_updateextendedproperty @name=N'MS_Description',@value=@description,@level0type=N'SCHEMA',@level0name=N'dbo',@level1type=N'TABLE',@level1name=@table,@level2type=N'COLUMN',@level2name=@column;
END ELSE BEGIN
IF @column IS NULL EXEC sys.sp_addextendedproperty @name=N'MS_Description',@value=@description,@level0type=N'SCHEMA',@level0name=N'dbo',@level1type=N'TABLE',@level1name=@table;
ELSE EXEC sys.sp_addextendedproperty @name=N'MS_Description',@value=@description,@level0type=N'SCHEMA',@level0name=N'dbo',@level1type=N'TABLE',@level1name=@table,@level2type=N'COLUMN',@level2name=@column;
END;
FETCH NEXT FROM descriptions INTO @table,@column,@description;
END; CLOSE descriptions; DEALLOCATE descriptions;
