// From the repository root: node examples/production-workflow/verify.cjs [path-to-index.html]
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { createRequire } = require('node:module')
const { pathToFileURL } = require('node:url')

const repo = path.resolve(__dirname, '../..')
const fromFrontend = createRequire(path.join(repo, 'src/frontend/package.json'))
const { chromium, expect } = fromFrontend('@playwright/test')
const file = path.resolve(process.argv[2] ?? path.join(repo, '../visual-previews/production-workflow/index.html'))
const output = path.join(repo, '.run/pf09-trace/workflow-sample-checks')

async function verify() {
  await fs.access(file)
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, offline: true })
  const page = await context.newPage()
  const requests = [], errors = [], checks = []
  page.on('request', (request) => {
    if (/^https?:/.test(request.url())) requests.push(request.url())
  })
  page.on('pageerror', (error) => errors.push(error.message))
  const button = (name) => page.getByRole('button', { name, exact: typeof name === 'string' })
  const node = (id) => page.locator(`.x6-node[data-cell-id="${encodeURIComponent(JSON.stringify(['node', id]))}"]`)
  const inspect = node('inspect')
  const detail = page.getByTestId('instance-detail')
  const name = page.getByLabel('活动名称', { exact: true })
  const x = page.getByLabel('横坐标', { exact: true })
  const y = page.getByLabel('纵坐标', { exact: true })
  async function assertDraft(label, left, top) {
    await expect(inspect).toContainText(label)
    await expect(name).toHaveValue(label)
    await expect(x).toHaveValue(left)
    await expect(y).toHaveValue(top)
  }
  function passed(message) {
    checks.push(message)
    console.log('PASS', message)
  }
  try {
    await page.goto(pathToFileURL(file).href)
    await expect(page.locator('.x6-node')).toHaveCount(7)
    await expect(page.locator('.x6-edge')).toHaveCount(7)
    await expect(button(/i-inspect-1/)).toBeVisible()
    await expect(button(/i-inspect-2/)).toBeVisible()
    passed('offline entry opens the seven-activity parallel graph with both inspection instances')

    await button('00:06 检验中').click()
    const join = node('join')
    const release = node('release')
    await expect(join).toContainText('等待')
    await expect(release).toContainText('等待')
    await button(/i-inspect-2/).click()
    await expect(detail).toContainText(/运行|进行中/)
    await button('00:08 已放行').click()
    await expect(join).toContainText('完成')
    await expect(release).toContainText('完成')
    await button(/i-inspect-2/).click()
    await expect(detail).toContainText(/完成/)
    // The failed-record fixture resolves after 120 ms. Switch to the faster
    // second record immediately and let both completion windows elapse.
    await button(/i-inspect-1/).click()
    await button('00:06 检验中').click()
    await button(/i-inspect-2/).click()
    await button('00:08 已放行').click()
    await expect(detail).toContainText('i-inspect-2')
    await page.waitForTimeout(180)
    await expect(detail).toContainText('i-inspect-2')
    await expect(detail).toContainText('已完成')
    await button(/i-inspect-1/).click()
    await expect(detail).toContainText('失败')
    await expect(detail).toContainText('i-inspect-1')
    passed('second inspection completes while the first failed inspection remains independently selectable')
    await page.screenshot({ path: path.join(output, 'playback.png'), fullPage: true })

    await button('定义草稿').click()
    await inspect.click()
    const oldName = await name.inputValue(), oldX = await x.inputValue(), oldY = await y.inputValue()
    const newName = '复核检验', newX = String(Number(oldX) + 37), newY = String(Number(oldY) + 19)
    await name.fill(newName)
    await x.fill(newX)
    await y.fill(newY)
    await button('应用修改').click()
    await assertDraft(newName, newX, newY)
    await button('撤销').click()
    await assertDraft(oldName, oldX, oldY)
    await button('重做').click()
    await assertDraft(newName, newX, newY)
    passed('one undo and one redo restore the full label and both coordinates')
    await button('保存草稿').click()
    const saved = await page.evaluate(() => localStorage.getItem('industrial-platform:standalone-workflow-sample:draft:1'))
    assert(saved)
    const definition = JSON.parse(saved)
    assert.deepEqual(Object.keys(definition).sort(), ['activities', 'id', 'layout', 'revisionNId', 'transitions'])
    assert.equal(definition.activities.find((a) => a.id === 'inspect').name, newName)
    assert(!/i-inspect-|"overlays"|"instances"/.test(saved), 'runtime data was persisted in the saved definition')
    await name.fill('未保存的临时改名')
    await button('应用修改').click()
    await expect(inspect).toContainText('未保存的临时改名')
    await button('重开草稿').click()
    await inspect.click()
    await assertDraft(newName, newX, newY)
    passed('reopening the saved draft restores the committed edit and discards the subsequent change')
    await page.screenshot({ path: path.join(output, 'draft.png'), fullPage: true })

    await button('运行回放').click()
    await expect(inspect).toContainText(oldName)
    await expect(inspect).not.toContainText(newName)
    await inspect.click()
    await button(/i-inspect-1/).click()
    await expect(detail).toContainText('失败')
    passed('playback stays on the published definition after editing the draft')
    assert.deepEqual(requests, [], 'offline artifact attempted HTTP(S) requests')
    assert.deepEqual(errors, [], 'page emitted an uncaught error')
    passed('no HTTP(S) requests or uncaught page errors')
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ file, browser: browser.version(), checks, requests, errors }, null, 2))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally {
    await browser.close()
  }
}

verify().catch((error) => { console.error(error); process.exitCode = 1 })
